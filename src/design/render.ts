import { SECTIONS, sectionsFor, type Level } from './sections.js';
import type { Project } from '../types.js';

const LEVEL_TITLE: Record<Level, string> = { hld: 'High-Level Design (HLD)', lld: 'Low-Level Design (LLD)' };

function githubSlug(heading: string): string {
  return heading
    .toLowerCase()
    .replace(/[^\p{L}\p{N}\s-]/gu, '')
    .replace(/\s/g, '-');
}

export function renderDoc(p: Project, level: Level): { markdown: string; missing: string[] } {
  const defs = sectionsFor(level);
  const missing: string[] = [];
  const headings = defs.map((d, i) => `${i + 1}. ${d.title}`);
  const out: string[] = [
    `# ${p.name} — ${LEVEL_TITLE[level]}`,
    '',
    `> Generated by Archforge on ${new Date().toISOString().slice(0, 10)} · project \`${p.id}\``,
    '',
    '## Contents',
    ...headings.map((h) => `- [${h}](#${githubSlug(h)})`),
    '',
  ];
  defs.forEach((d, i) => {
    out.push(`## ${headings[i]}`, '');
    const s = p.sections[d.id];
    if (!s) {
      missing.push(d.id);
      out.push('_This section has not been generated yet._', '');
    } else {
      if (s.answersVersion < p.answersVersion) out.push('> ⚠️ Requirements changed after this section was written — regenerate to refresh it.', '');
      out.push(s.content.trim(), '');
    }
  });
  return { markdown: out.join('\n'), missing };
}

export function renderIndex(p: Project, files: string[], missing: string[]): string {
  const assumptions = assumptionList(p);
  return [
    `# ${p.name} — Architecture Package`,
    '',
    p.description.trim(),
    '',
    '## Documents',
    '- [High-Level Design](hld.md)',
    '- [Low-Level Design](lld.md)',
    '- [Browser viewer with rendered diagrams](viewer.html) (needs internet for the Markdown/Mermaid CDN scripts)',
    '- `requirements.json` — raw questionnaire answers (machine-readable)',
    '- `diagrams/` — every Mermaid diagram as a standalone `.mmd` file',
    '',
    '## Requirements captured',
    requirementsMarkdown(p),
    '',
    '## Assumptions to confirm',
    assumptions.length ? assumptions.map((a) => `- ${a}`).join('\n') : '_All answers were provided explicitly._',
    '',
    missing.length ? `## Not generated yet\n${missing.map((m) => `- \`${m}\``).join('\n')}\n` : '',
    '---',
    `Files in this package: ${files.length}. Re-run \`archforge_generate_design\` + \`archforge_export\` after changing requirements.`,
  ].join('\n');
}

