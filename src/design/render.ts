export interface ExportResult {
  dir: string;
  files: string[];
  missing: string[];
  stale: string[];
}

export function writeExport(p: Project, dir: string): ExportResult {
  fs.mkdirSync(path.join(dir, 'diagrams'), { recursive: true });
  const files: string[] = [];
  const write = (rel: string, content: string) => {
    const f = path.join(dir, rel);
    fs.mkdirSync(path.dirname(f), { recursive: true });
    fs.writeFileSync(f, content);
    files.push(f);
  };

  const hld = renderDoc(p, 'hld');
  const lld = renderDoc(p, 'lld');
  const missing = [...hld.missing, ...lld.missing];
  const stale = SECTIONS.filter((d) => p.sections[d.id] && p.sections[d.id].answersVersion < p.answersVersion).map((d) => d.id);

  write('hld.md', hld.markdown);
  write('lld.md', lld.markdown);

  for (const d of SECTIONS) {
    const s = p.sections[d.id];
    if (!s) continue;
    extractDiagrams(s.content).forEach((dg, i) => write(path.join('diagrams', `${d.id}-${i + 1}.mmd`), dg.code + '\n'));
  }
  write(
    'requirements.json',
    JSON.stringify({ project: { id: p.id, name: p.name, description: p.description }, answers: p.answers }, null, 2) + '\n',
  );

  const index = renderIndex(p, files, missing);
  write('README.md', index);
  write('viewer.html', viewerHtml(p, { hld: hld.markdown, lld: lld.markdown, index }));
  return { dir, files, missing, stale };
}
